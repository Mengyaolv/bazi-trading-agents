from typing import Annotated
from typing_extensions import TypedDict
from langgraph.graph import MessagesState


# 八字分析辩论状态
class BaziDebateState(TypedDict):
    traditional_history: Annotated[
        str, "Traditional Analyst's conversation history"
    ]  # 传统命理师对话历史
    psychology_history: Annotated[
        str, "Psychology Analyst's conversation history"
    ]  # 心理学分析师对话历史
    history: Annotated[str, "Conversation history"]  # 对话历史
    current_response: Annotated[str, "Latest response"]  # 最新回复
    judge_decision: Annotated[str, "Final judge decision"]  # 最终判断
    count: Annotated[int, "Length of the current conversation"]  # 对话长度


# 八字分析状态
class BaziAnalysisState(MessagesState):
    # 输入信息
    birth_info: Annotated[str, "Birth information (year, month, day, hour, gender)"]
    analysis_date: Annotated[str, "Date of analysis"]

    sender: Annotated[str, "Agent that sent this message"]

    # 分析步骤
    chart_report: Annotated[str, "Report from the Chart Calculator (四柱排盘)"]
    day_master_report: Annotated[str, "Report from the Day Master Analyst (日主分析)"]
    ten_gods_report: Annotated[str, "Report from the Ten Gods Analyst (十神分析)"]
    pattern_report: Annotated[str, "Report from the Pattern Analyst (格局分析)"]
    useful_god_report: Annotated[str, "Report from the Useful God Analyst (用神分析)"]
    luck_cycle_report: Annotated[str, "Report from the Luck Cycle Analyst (大运分析)"]

    # 辩论步骤
    bazi_debate_state: Annotated[
        BaziDebateState, "Current state of the debate on interpretation"
    ]
    interpretation_plan: Annotated[str, "Plan generated by the Interpreter"]

    # 心理学翻译步骤
    psychology_translation: Annotated[str, "Psychology translation of the analysis"]

    # 最终输出
    final_analysis: Annotated[str, "Final comprehensive analysis"]
